import { test, expect } from '@playwright/test';
import * as OTPAuth from 'otpauth';
import { mkdirSync } from 'node:fs';
async function signIn(page: import('@playwright/test').Page, email: string) {
  await page.goto('/login');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Long-test-password-123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
}
test('customers download assigned latest and older releases', async ({ page, context }) => {
  await signIn(page, 'customer@test.example');
  await expect(page.getByRole('heading', { name: 'Your app library' })).toBeVisible();
  mkdirSync('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/catalog-desktop.png', fullPage: true, caret: 'initial' });
  await expect(page.getByText('Other Mobile', { exact: true })).toHaveCount(0);
  const forbidden = await page.request.get(`/api/releases/${process.env.E2E_FOREIGN_RELEASE_ID}/download`);
  expect(forbidden.status()).toBe(403);
  expect((await page.request.get('/api/admin/users')).status()).toBe(403);
  await page.getByRole('link', { name: 'View releases' }).first().click();
  await expect(page.getByText('A faster dashboard and better reporting.')).toBeVisible();
  await expect(page.getByRole('button', { name: /Download/ })).toHaveCount(2);
  const promise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download v1.0' }).click();
  const download = await promise;
  expect(download.suggestedFilename()).toBe('acme-1.apk');
  mkdirSync('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/customer-desktop.png', fullPage: true, caret: 'initial' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/customer-mobile.png', fullPage: true, caret: 'initial' });
  const access = (await context.cookies()).find(cookie => cookie.name === 'payana_access')!;
  await context.addCookies([{ ...access, value: '', expires: 1 }]);
  const second = await context.newPage();
  await Promise.all([page.goto('/renew?next=%2Fcatalog'), second.goto('/renew?next=%2Fcatalog')]);
  await expect(page.getByRole('heading', { name: 'Your app library' })).toBeVisible();
  await expect(second.getByRole('heading', { name: 'Your app library' })).toBeVisible();
  expect((await page.request.get(`/api/releases/${process.env.E2E_RELEASE_ID}/download`)).status()).toBe(200);
});
test('viewers browse all apps but cannot download', async ({ page }) => {
  await signIn(page, 'viewer@test.example');
  await expect(page.getByText('Other Mobile', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'View releases' }).first().click();
  await expect(page.getByRole('button', { name: /Download/ })).toHaveCount(0);
  const response = await page.request.get(`/api/releases/${process.env.E2E_RELEASE_ID}/download`);
  expect(response.status()).toBe(403);
});
