test('first admin enrollment displays one-use recovery codes and recovery works', async ({ page }) => {
  await signIn(page, 'newadmin@test.example');
  await expect(page.getByRole('heading', { name: 'Secure your admin account' })).toBeVisible();
  const secret = await page.locator('code.secret').textContent();
  const totp = new OTPAuth.TOTP({ secret: OTPAuth.Secret.fromBase32(secret!), digits: 6, period: 30 });
  await page.getByLabel('Authenticator code').fill(totp.generate());
  await page.getByRole('button', { name: 'Activate authenticator' }).click();
  await expect(page.getByRole('heading', { name: 'Save your recovery codes' })).toBeVisible();
  await expect(page.locator('.code-grid code')).toHaveCount(10);
  const recoveryCode = await page.locator('.code-grid code').first().textContent();
  await page.getByRole('button', { name: 'I saved my codes' }).click();
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page, 'newadmin@test.example');
  await page.getByRole('button', { name: 'Use a recovery code' }).click();
  await page.getByLabel('Recovery code').fill(recoveryCode!);
  await page.getByRole('button', { name: 'Verify and sign in' }).click();
  await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page, 'newadmin@test.example');
  await page.getByRole('button', { name: 'Use a recovery code' }).click();
  await page.getByLabel('Recovery code').fill(recoveryCode!);
  await page.getByRole('button', { name: 'Verify and sign in' }).click();
  await expect(page.locator('form').getByRole('alert')).toContainText('Invalid or already used recovery code');
});
